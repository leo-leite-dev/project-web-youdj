-- pgTAP security tests for public room codes and the public lookup RPC.
-- Run with: supabase test db
--
-- Focus: code column guarantees, least privilege, and the limited public
-- function. Cross-DJ table isolation and anon table blocking stay covered by
-- rooms_rls.test.sql and are not repeated here.

begin;

select plan(27);

-- Fixtures: two DJs with profiles.
insert into auth.users (
  instance_id,
  id,
  aud,
  role,
  email,
  email_confirmed_at,
  raw_app_meta_data,
  raw_user_meta_data,
  is_anonymous
)
values
  (
    '00000000-0000-0000-0000-000000000000',
    '11111111-1111-1111-1111-111111111111',
    'authenticated',
    'authenticated',
    'dj-a@example.test',
    now(),
    '{"provider":"email","providers":["email"]}'::jsonb,
    '{}'::jsonb,
    false
  ),
  (
    '00000000-0000-0000-0000-000000000000',
    '22222222-2222-2222-2222-222222222222',
    'authenticated',
    'authenticated',
    'dj-b@example.test',
    now(),
    '{"provider":"email","providers":["email"]}'::jsonb,
    '{}'::jsonb,
    false
  );

insert into public.dj_profiles (id, display_name)
values
  ('11111111-1111-1111-1111-111111111111', 'DJ Alpha'),
  ('22222222-2222-2222-2222-222222222222', 'DJ Beta');

-- Room fixtures: one code generated by the trigger, one explicit code.
insert into public.rooms (dj_id, name)
values ('11111111-1111-1111-1111-111111111111', 'Festa Gerada');

insert into public.rooms (dj_id, name, code)
values ('22222222-2222-2222-2222-222222222222', 'Festa Fixa', 'FIXED001AB');

-- Structural guarantees.
select ok(
  (select is_nullable = 'NO'
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'rooms'
      and column_name = 'code'),
  'code column is not null'
);

select ok(
  exists (
    select 1
    from pg_constraint
    where conrelid = 'public.rooms'::regclass
      and conname = 'rooms_code_key'
      and contype = 'u'
  ),
  'code has a unique constraint'
);

select ok(
  exists (
    select 1
    from pg_constraint
    where conrelid = 'public.rooms'::regclass
      and conname = 'rooms_code_check'
      and contype = 'c'
  ),
  'code format is enforced by a check constraint'
);

select ok(
  exists (
    select 1
    from pg_trigger
    where tgrelid = 'public.rooms'::regclass
      and tgname = 'set_rooms_public_code'
      and not tgisinternal
      and (tgtype & 2) = 2
  ),
  'before insert trigger fills missing codes'
);

select ok(
  exists (
    select 1
    from pg_trigger
    where tgrelid = 'public.rooms'::regclass
      and tgname = 'set_rooms_updated_at'
      and tgenabled <> 'D'
      and not tgisinternal
  ),
  'updated_at trigger remains enabled after code backfill'
);

select ok(
  exists (
    select 1
    from pg_proc
    where proname = 'generate_room_code'
      and pronamespace = 'public'::regnamespace
  ),
  'generate_room_code function exists'
);

select ok(
  (select prosecdef
    from pg_proc
    where oid = 'public.room_by_code(text)'::regprocedure),
  'room_by_code runs as security definer'
);

select ok(
  (select 'search_path=""' = any(proconfig)
    from pg_proc
    where oid = 'public.room_by_code(text)'::regprocedure),
  'room_by_code has a locked empty search_path'
);

-- Least privilege on the new column and functions.
select ok(
  not has_column_privilege('anon', 'public.rooms', 'code', 'SELECT'),
  'anon cannot read the code column'
);

select ok(
  has_column_privilege('authenticated', 'public.rooms', 'code', 'SELECT'),
  'authenticated can read their own room code'
);

select ok(
  not has_column_privilege('authenticated', 'public.rooms', 'code', 'INSERT'),
  'authenticated cannot choose the code on insert'
);

select ok(
  not has_column_privilege('authenticated', 'public.rooms', 'code', 'UPDATE'),
  'authenticated cannot change the code on update'
);

select ok(
  has_function_privilege('anon', 'public.room_by_code(text)', 'EXECUTE'),
  'anon can execute the public lookup'
);

select ok(
  has_function_privilege('authenticated', 'public.room_by_code(text)', 'EXECUTE'),
  'authenticated can execute the public lookup'
);

select ok(
  not has_function_privilege('anon', 'public.generate_room_code()', 'EXECUTE')
  and not has_function_privilege('authenticated', 'public.generate_room_code()', 'EXECUTE')
  and not has_function_privilege('anon', 'public.set_rooms_public_code()', 'EXECUTE')
  and not has_function_privilege('authenticated', 'public.set_rooms_public_code()', 'EXECUTE')
  and not exists (
    select 1
    from pg_proc as p
    cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) as acl
    where p.oid = 'public.room_by_code(text)'::regprocedure
      and acl.grantee = 0
      and acl.privilege_type = 'EXECUTE'
  ),
  'only the approved client roles can execute the public RPC; helpers stay private'
);

-- Code generation behavior (table owner context).
select results_eq(
  $$select code ~ '^[A-Z0-9]{10}$' and length(code) = 10
    from public.rooms
    where name = 'Festa Gerada'$$,
  $$select true$$,
  'trigger generates a well-formed public code'
);

select results_eq(
  $$select code from public.rooms where name = 'Festa Fixa'$$,
  $$select 'FIXED001AB'::text$$,
  'an explicitly provided code is preserved'
);

select throws_ok(
  $$insert into public.rooms (dj_id, name, code)
    values ('22222222-2222-2222-2222-222222222222', 'Duplicada', 'FIXED001AB')$$,
  '23505',
  null,
  'duplicate public codes are rejected'
);

select throws_ok(
  $$insert into public.rooms (dj_id, name, code)
    values ('22222222-2222-2222-2222-222222222222', 'Formato Ruim', 'ab1')$$,
  '23514',
  null,
  'codes outside the public format are rejected'
);

-- Owner operations through the API role.
select set_config(
  'request.jwt.claims',
  '{"sub":"11111111-1111-1111-1111-111111111111","role":"authenticated","is_anonymous":false}',
  true
);
set local role authenticated;

select throws_ok(
  $$insert into public.rooms (dj_id, name, code)
    values ('11111111-1111-1111-1111-111111111111', 'Escolha Propria', 'ABCDEF1234')$$,
  '42501',
  null,
  'authenticated cannot choose the room code'
);

select lives_ok(
  $$insert into public.rooms (dj_id, name)
    values ('11111111-1111-1111-1111-111111111111', 'Sala Nova')$$,
  'authenticated insert without a code succeeds via the trigger'
);

select throws_ok(
  $$update public.rooms
    set code = 'ZZ1234WXYZ'
    where dj_id = '11111111-1111-1111-1111-111111111111' and name = 'Sala Nova'$$,
  '42501',
  null,
  'authenticated cannot change the room code'
);

select results_eq(
  $$select code is not null
    from public.rooms
    where dj_id = '11111111-1111-1111-1111-111111111111' and name = 'Sala Nova'$$,
  $$select true$$,
  'owner can read the generated code'
);

reset role;

-- Anonymous point lookup exposes only the three public fields.
select set_config('request.jwt.claims', '{"role":"anon"}', true);
set local role anon;

select results_eq(
  $$select code, name, status from public.room_by_code('fixed001ab')$$,
  $$select 'FIXED001AB'::text, 'Festa Fixa'::text, 'active'::text$$,
  'anon lookup normalizes input and returns only public fields'
);

select is_empty(
  $$select * from public.room_by_code('ZZZZZZZZZZ')$$,
  'unknown code returns no rows'
);

select is_empty(
  $$select * from public.room_by_code(null)$$,
  'null code returns no rows'
);

reset role;

-- Any authenticated DJ can read public room data by code.
select set_config(
  'request.jwt.claims',
  '{"sub":"11111111-1111-1111-1111-111111111111","role":"authenticated","is_anonymous":false}',
  true
);
set local role authenticated;

select results_eq(
  $$select name from public.room_by_code('FIXED001AB')$$,
  $$select 'Festa Fixa'::text$$,
  'another DJ can read public room data by code'
);

reset role;

select * from finish();

rollback;
